/**
 * 기능 플래그 — **프론트와 백이 같은 값을 본다.**
 *
 * 앱마다 따로 두면 "프론트엔 버튼이 있는데 백엔드는 막혀 있다" 는 형태로 어긋난다.
 * 여기 한 줄을 고치면 두 앱이 함께 바뀐다 (contracts 는 두 앱에 함께 빌드된다).
 */

/**
 * 게스트 체험(무입력 입장) 허용 여부.
 *
 * - `true`  — 「로그인 없이 바로 체험하기」 버튼이 보이고, `POST /auth/guest` 가 열린다.
 * - `false` — 버튼이 사라지고 엔드포인트는 403 이다. 닉네임·비밀번호 입력 화면만 남는다.
 *
 * 2026-09-20 도입 배경: 대회 심사·투표 기간(9/21~) 동안 심사위원이 **입력 없이** 핵심 기능
 * (내 얼굴 합성 동화)에 닿을 수 있어야 한다는 운영팀 요구사항.
 *
 * ⚠️ 이 값은 **빌드 시점에 번들에 박힌다.** 서버 환경변수로는 프론트 버튼을 못 없앤다.
 *    백엔드만 즉시 잠그려면 `GUEST_ACCESS_ENABLED=false` 환경변수를 주입한다 (런타임 우선).
 */
export const GUEST_ACCESS_ENABLED = true;

/**
 * 비로그인 방문자를 **버튼 없이 자동으로** 게스트 입장시킨다.
 *
 * - `true`  — 사이트에 들어오면 곧바로 임시 계정이 생기고 로그인 상태가 된다. 심사위원은 아무것도 누르지 않는다.
 * - `false` — 자동 입장은 하지 않고 「닉네임 없이 바로 체험하기」 버튼으로만 들어간다.
 *
 * ⚠️ `GUEST_ACCESS_ENABLED` 가 `false` 면 이 값과 무관하게 동작하지 않는다 (상위 스위치다).
 * ⚠️ **켜면 방문자 수만큼 계정 행이 쌓인다.** 대회가 끝나면 끄는 것을 전제로 한 값이다.
 *
 * 🚫 자동 입장에는 세 가지 함정이 있고 `useGuestAutoEnter` 가 전부 막고 있다 —
 *    ① 로그인 화면에서 돌면 **로그인 자체가 불가능**해지고
 *    ② 로그아웃 직후에 돌면 **로그아웃이 안 되는 것처럼 보이며**
 *    ③ 실패를 재시도하면 레이트리밋에 걸려 화면이 멈춘다.
 *    이 플래그만 켜고 그 방어를 걷어내지 말 것.
 */
export const GUEST_AUTO_ENTER = true;

